def seed():
    with get_cursor(commit=True) as cursor:
        # 1. Insertar fundaciones si no existen por nombre
        print("Insertando nuevas fundaciones...")
        for f in nuevas_fundaciones:
            nombre, ciudad, direccion, telefono, email = f
            cursor.execute("SELECT id FROM refugios WHERE nombre = %s", (nombre,))
            if not cursor.fetchone():
                cursor.execute("""
                    INSERT INTO refugios (nombre, ciudad, direccion, telefono, email)
                    VALUES (%s, %s, %s, %s, %s)
                """, (nombre, ciudad, direccion, telefono, email))
                print(f"  + Refugio agregado: {nombre} ({ciudad})")

        # Obtener lista de todos los IDs de refugios
        cursor.execute("SELECT id, nombre, ciudad FROM refugios")
        refugios = cursor.fetchall()
        print(f"Total refugios actuales: {len(refugios)}")

        # 2. Insertar nuevas mascotas
        print("\nInsertando nuevas mascotas...")
        ref_idx = 0
        inserted_pets = []
        for p in nuevas_mascotas:
            cursor.execute("SELECT id FROM mascotas WHERE nombre = %s AND ciudad = %s", (p["nombre"], p["ciudad"]))
            existing = cursor.fetchone()
            if existing:
                continue

            # Asignar refugio rotativo
            assigned_ref = refugios[ref_idx % len(refugios)]
            ref_idx += 1

            cursor.execute("""
                INSERT INTO mascotas (
                    refugio_id, nombre, tipo, edad, sexo, tamano, raza, ciudad,
                    descripcion, personalidad, nivel_energia, compatible_ninos,
                    compatible_mascotas, vacunado, desparasitado, esterilizado,
                    estado, foto_url
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            """, (
                assigned_ref["id"],
                p["nombre"],
                p["tipo"],
                p["edad"],
                p["sexo"],
                p["tamano"],
                p["raza"],
                p["ciudad"],
                p["descripcion"],
                p["personalidad"],
                p["nivel_energia"],
                p["compatible_ninos"],
                p["compatible_mascotas"],
                p["vacunado"],
                p["desparasitado"],
                p["esterilizado"],
                p["estado"],
                p["foto_url"],
            ))
            pet_id = cursor.lastrowid
            inserted_pets.append((pet_id, p["nombre"], p["tipo"]))
            print(f"  + Mascota agregada: {p['nombre']} (#{pet_id} - {p['tipo']}) en {assigned_ref['nombre']}")

            # 3. Crear controles en historial_veterinario para la nueva mascota
